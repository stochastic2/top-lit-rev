"""Specialize the ideal check algebra of arXiv:2610.03920 to C4-Helix SWAP.

Uses whole inner-C4 groups as controller sets and direct dressing paths.
Certifies graph constants, a check schedule, and a static distance witness.
This does NOT certify a physical circuit fault distance or a decoder.
Only Python's standard library is needed.
"""
from collections import Counter
from itertools import combinations
from pathlib import Path
from fractions import Fraction
import json
import re

ROOT = Path(__file__).resolve().parent.parent
source = (ROOT / 'arXiv-2609.03194v1/appendix.tex').read_text()
table = source.split(r'\begin{minipage}{0.6\textwidth}')[1].split(r'\end{minipage}')[0]
rows = []
for line in table.splitlines():
    symbols = re.findall(r'\$(X|Z|\\cdot)\$', line)
    if len(symbols) == 20:
        rows.append([q for q, symbol in enumerate(symbols) if symbol != r'\cdot'])
assert len(rows) == 24 and rows[:10] == rows[10:20]
R = rows[:10]
V = list('abcde')
edges = {q: tuple(v for v, support in zip(V, R[5:]) if q in support)
         for q in range(20)}
pair_edges = {pair: [q for q, endpoints in edges.items() if endpoints == pair]
              for pair in combinations(V, 2)}
assert all(len(qs) == 2 for qs in pair_edges.values())
phi = {q: V[q // 4] for q in range(20)}
roots = V + V


def mask(qs):
    return sum(1 << q for q in qs)


def span(gs):
    values = {0}
    for g in gs:
        values |= {v ^ g for v in values}
    return values


def parity(x):
    return x.bit_count() % 2


def cut(t):
    return mask(q for q, (u, v) in edges.items()
                if ((t >> V.index(u)) ^ (t >> V.index(v))) & 1)


paths = [[0 if phi[q] == roots[i] else
          1 << pair_edges[tuple(sorted((phi[q], roots[i])))][0]
          for q in support] for i, support in enumerate(R)]
cycles = list(pair_edges.values()) + [
    [pair_edges[('a', u)][0], pair_edges[(u, v)][0], pair_edges[('a', v)][0]]
    for u, v in combinations(V[1:], 2)]
cycle_space = span(map(mask, cycles))
assert len(cycle_space) == 2**16
assert all(not any(sum(v in edges[q] for q in cycle) % 2 for v in V)
           for cycle in cycles)
cuts = {cut(t): t for t in range(32) if not t & 1}
assert len(cuts) == 16
cut_distance = min(w.bit_count() for w in cuts if w)
h = min(Fraction(cut(t).bit_count(), min(t.bit_count(), 5-t.bit_count()))
        for t in range(1, 31))
assert cut_distance == 8 and h == 6
cycle_usage = Counter(q for cycle in cycles for q in cycle)

# For a fixed gauge-Z word, a dressed X or Z check is a Pauli string
# distributed between B and C. X/Z commutation has one minus sign for
# each shared q assigned to the same copy. The original overlap is even,
# leaving the linear gauge phase sum_q(path_i(q) + path_j(q)).
commutators = set()
for i in range(10):
    for j in range(10):
        assert len(set(R[i]) & set(R[j])) % 2 == 0
        ci = dict(zip(R[i], paths[i]))
        cj = dict(zip(R[j], paths[j]))
        phase = 0
        for q in set(ci) & set(cj):
            phase ^= ci[q] ^ cj[q]
        if phase:
            assert phase in cycle_space
            commutators.add(phase)
        # Check the symbolic phase identity on every gauge edge basis vector.
        for z in [0] + [1 << q for q in range(20)]:
            overlap = sum(parity(z & ci[q]) == parity(z & cj[q])
                          for q in set(ci) & set(cj)) % 2
            assert overlap == parity(z & phase)

# Every G_v commutes with all D_s except at s's root, where its group
# commutator is exactly N_s = S_B,s S_C,s. Same-type D checks commute
# globally, because all conditional matter Paulis have the same type.
for i in range(10):
    for v in V:
        for q, path in zip(R[i], paths[i]):
            assert (int(phi[q] == v) ^ parity(path & cut(1 << V.index(v)))) == int(roots[i] == v)
extra = commutators - set(map(mask, cycles))
assert len(commutators) == 5 and len(extra) == 2

# Exact base-code distance: C-perp/C is generated by the Table-I logical
# X supports; the CSS X and Z matrices are identical. A nontrivial mixed
# Pauli has at least the weight of its nontrivial X or Z component.
C = span(map(mask, R))
perp = span(list(map(mask, R)) + list(map(mask, rows[20:22])))
assert len(C) == 512 and len(perp) == 2048
assert all(all(parity(x & mask(r)) == 0 for r in R) for x in perp)
d = min(x.bit_count() for x in perp - C)
assert d == 6

# Static lower-bound certificate (analytical argument): in the gauging
# isometry W = (1/4) sum_{t_a=0} |cut(t)> V_t, a gauge Pauli X component
# smaller than cut_distance cannot connect distinct flat fields. With no
# gauge X, W^dagger E W is an average of V_t^dagger E_m V_t with signs.
# All V_t are physical permutations and preserve Pauli weight. Thus any
# physical error of weight < min(d, cut_distance) compresses to a scalar.
static_lower_bound = min(d, cut_distance)

# Upper bound: Table-I logical X_0 on B is a weight-six physical operator.
# Enumerate its 16 permutations. Only four survive original code
# projection, each as X_0 on B; all other terms have nonzero syndrome.
x0 = mask(rows[20])
assert x0.bit_count() == 6
survivors = Counter()
for t in cuts.values():
    xb = mask(q for q in rows[20] if not (t >> (q // 4)) & 1)
    xc = x0 ^ xb
    if all(not parity(x & mask(r)) for x in (xb, xc) for r in R):
        survivors[(xb, xc)] += 1
assert survivors == {(x0, 0): 4}
# Hence W^dagger X_B0 W = (1/4) P_+ X_B0 P_+; this is non-scalar.
assert static_lower_bound == x0.bit_count() == 6

report = {
    'scope': 'Ideal check algebra and static physical-qubit distance only; no circuit fault-distance claim',
    'paper': 'arXiv:2610.03920v1, Magic Quantum Code Surgery',
    'controller_assignment': {v: list(range(4*i, 4*i+4)) for i, v in enumerate(V)},
    'graph_degree': 8,
    'graph_cheeger_constant': str(h),
    'nonzero_cut_minimum_weight': cut_distance,
    'cycle_rank': 16,
    'cycle_check_maximum_weight': max(map(len, cycles)),
    'cycle_basis_maximum_edge_incidence': max(cycle_usage.values()),
    'maximum_matter_vertex_set_size_nu': 8,
    'dressing_paths': [[[q for q in range(20) if p >> q & 1] for p in ps] for ps in paths],
    'distinct_nonidentity_DX_DZ_commutators': [[q for q in range(20) if p >> q & 1] for p in sorted(commutators)],
    'additional_redundant_cycle_checks': [[q for q in range(20) if p >> q & 1] for p in sorted(extra)],
    'central_Pauli_checks_listed': 20 + 16 + len(extra),
    'central_Pauli_checks_independent': 18 + 16,
    'remaining_checks_listed': {'Gauss': 5, 'dressed_X_B': 10, 'dressed_Z_B': 10},
    'gauged_round_subrounds': ['central Pauli', 'Gauss', 'dressed X_B', 'dressed Z_B'],
    'paper_unoptimized_schedule_rounds': {'before': 6, 'gauged': 6, 'after': 6},
    'static_gauged_code_distance': 6,
    'static_lower_bound_ingredients': {'matter_code_distance': d, 'gauge_cut_distance': cut_distance, 'local_SWAPS_preserve_Pauli_weight': True},
    'weight_six_witness': {'operator': 'logical_X0_on_B', 'physical_support': rows[20], 'surviving_permutations': 4, 'total_permutations': 16, 'compressed_operator': '(1/4) P_plus X_B0 P_plus'},
    'physical_circuit_two_fault_guarantee_established': False,
    'decoder_for_randomized_detectors_implemented': False,
}
dest = ROOT / 'output/c4-helix-magic-code-surgery-audit.json'
dest.write_text(json.dumps(report, indent=2) + '\n')
print('Graph: h=6, degree=8, cut distance=8, cycle rank=16.')
print('Gauged round: 38 central Pauli checks, then 5 G, 10 D_X, 10 D_Z.')
print('Extra redundant cycle checks:', report['additional_redundant_cycle_checks'])
print('Static gauged-code physical-qubit distance = 6 (permutation argument + exact witness).')
print('No physical circuit fault-tolerance guarantee established by this audit.')
print('Saved', dest)
